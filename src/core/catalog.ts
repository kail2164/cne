export function getRifleForCaliber(familyId: string): Weapon | undefined {
  const PRIMARY: Record<string, string> = {
    "762x54r": "mosin-m91",
    "3006": "springfield-m1903",
    "303br": "lee-enfield-smle",
    "8x50r": "lebel-m1886",
    "792x57": "gewehr-98",
    "75x54": "fm-24-29",
    "65x52": "carcano-m91",
    "65x50sr": "type-38",
    "7x57": "mauser-1893",
    "65x55": "mauser-m96",
    "75x53": "schmidt-rubin-1896",
    "75x55": "schmidt-rubin-1911",
    "8x50mann": "mannlicher-m1895",
    "8x56r": "mannlicher-m9530",
    "765x53": "mauser-1889",
    "65x54": "schonauer-m1903",
    "65x53r": "mannlicher-m95-dutch",
  };
  const preferred = PRIMARY[familyId];
  if (preferred) {
    const w = getRifle(preferred);
    if (w) return w;
  }
  return RIFLES.find((r) => r.caliberId === familyId);
}

/** All rifles for a family (primary + researched seconds). */
export function getRiflesForCaliber(familyId: string): Weapon[] {
  return RIFLES.filter((r) => r.caliberId === familyId);
}

/**
 * Effective ballistic pair.
 * Damage is caliber base plus the weapon's flat bonus.
 * Penetration is millimeters of mild steel at 100 m: the rifle's FMJ figure,
 * scaled by how this load compares with that family's FMJ.
 */
export function effectiveDamage(weaponId: string, ammoCaliberId: string): number {
  const w = getRifle(weaponId);
  const c = getCaliber(ammoCaliberId);
  if (!w || !c) return 0;
  return c.baseDamage + w.damage;
}

export function effectivePenetration(weaponId: string, ammoCaliberId: string): number {
  const w = getRifle(weaponId);
  const c = getCaliber(ammoCaliberId);
  if (!w || !c) return 0;
  const fmj = getAmmo(c.familyId, "fmj");
  const scale = fmj && fmj.basePenetration > 0 ? c.basePenetration / fmj.basePenetration : 1;
  return Number((w.penetration * scale).toFixed(2));
}

